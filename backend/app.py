def alchemy_rpc(method: str, params: List[Any]) -> Dict[str, Any]:
    if not ALCHEMY_URL:
        raise HTTPException(
            status_code=500,
            detail="ALCHEMY_API_KEY is missing in block/.env",
        )

    try:
        response = requests.post(
            ALCHEMY_URL,
            json={
                "jsonrpc": "2.0",
                "id": 1,
                "method": method,
                "params": params,
            },
            timeout=30,
        )

        response.raise_for_status()

        data = response.json()

    except requests.RequestException as exc:
        raise HTTPException(
            status_code=502,
            detail=f"Alchemy request failed: {str(exc)}",
        )

    if "error" in data:
        raise HTTPException(
            status_code=502,
            detail=str(data["error"]),
        )

    return data.get("result", {})


