# NORMALIZE ALCHEMY TRANSFER
# ============================================================

def normalize_transfer(
    tx: Dict[str, Any],
    searched_wallet: str,
    hop: int,
) -> Optional[Dict[str, Any]]:

    source = str(tx.get("from") or "").lower()
    target = str(tx.get("to") or "").lower()

    if not source or not target:
        return None

    if not source.startswith("0x") or not target.startswith("0x"):
        return None

    raw_asset = tx.get("asset") or "ETH"

    if raw_asset == "0x":
        raw_asset = "ETH"

    asset = format_asset(raw_asset)

    amount = safe_float(tx.get("value"))

    if amount <= 0:
        return None

    src_res = resolve_entity(source)
    tgt_res = resolve_entity(target)
    print(f"API Address: {tx.get('from')} -> {source} -> {'matched' if src_res.get('known') else 'not matched'} -> {src_res.get('label')}")
    print(f"API Address: {tx.get('to')} -> {target} -> {'matched' if tgt_res.get('known') else 'not matched'} -> {tgt_res.get('label')}")

    return {
        "id": tx.get("hash")
        or f"{source[:10]}-{target[:10]}-{tx.get('blockNum')}",

        "hash": tx.get("hash"),

        "source": source,
        "target": target,

        "source_label": src_res.get("label") if src_res.get("known") else short_address(source),
        "target_label": tgt_res.get("label") if tgt_res.get("known") else short_address(target),

        "amount": amount,
        "asset": asset,

        "timestamp": (
            tx.get("metadata", {})
            .get("blockTimestamp")
        ),

        "block": tx.get("blockNum"),

        "category": tx.get("category"),

        "direction": (
            "outgoing"
            if source == searched_wallet
            else "incoming"
        ),

        "hop": hop,
    }


