# MAIN TRACE ENGINE
# ============================================================

def trace_wallet(
    searched_wallet: str,
    max_hops: int,
) -> Dict[str, Any]:

    visited = {
        searched_wallet
    }

    queue = deque([
        (
            searched_wallet,
            0,
        )
    ])

    all_transactions: List[Dict[str, Any]] = []

    wallet_hops: Dict[str, int] = {
        searched_wallet: 0
    }

    # --------------------------------------------------------
    # BFS MULTI-HOP TRACE
    # --------------------------------------------------------

    while queue:

        current_wallet, current_hop = queue.popleft()

        if current_hop >= max_hops:
            continue

        if len(visited) >= MAX_WALLETS:
            break

        activity = fetch_wallet_activity(
            current_wallet,
            current_hop,
        )

        # Deduplicate transactions
        existing_hashes = {
            tx.get("hash")
            for tx in all_transactions
            if tx.get("hash")
        }

        for tx in activity:

            if len(all_transactions) >= MAX_TOTAL_TX:
                break

            if (
                tx.get("hash")
                and tx["hash"] in existing_hashes
            ):
                continue

            all_transactions.append(tx)

            destination = tx["target"]

            # Only follow outgoing destinations.
            if (
                tx["source"] == current_wallet
                and destination not in visited
                and destination != searched_wallet
                and len(visited) < MAX_WALLETS
            ):
                visited.add(destination)

                wallet_hops[destination] = (
                    current_hop + 1
                )

                queue.append(
                    (
                        destination,
                        current_hop + 1,
                    )
                )

    # --------------------------------------------------------
    # REMOVE INVALID / DUPLICATE TRANSACTIONS
    # --------------------------------------------------------

    unique_transactions = {}

    for tx in all_transactions:

        key = (
            tx.get("hash")
            or (
                tx["source"],
                tx["target"],
                tx["amount"],
                tx["asset"],
            )
        )

        unique_transactions[key] = tx

    all_transactions = list(
        unique_transactions.values()
    )

    # --------------------------------------------------------
    # NODE METRICS
    # --------------------------------------------------------

    node_transactions: Dict[str, List[Dict[str, Any]]] = (
        defaultdict(list)
    )

    outgoing_by_node = defaultdict(float)
    incoming_by_node = defaultdict(float)
    flow_by_node = defaultdict(float)
    counterparties = defaultdict(set)

    for tx in all_transactions:

        source = tx["source"]
        target = tx["target"]

        node_transactions[source].append(tx)
        node_transactions[target].append(tx)

        outgoing_by_node[source] += tx["amount"]
        incoming_by_node[target] += tx["amount"]

        flow_by_node[source] += tx["amount"]
        flow_by_node[target] += tx["amount"]

        counterparties[source].add(target)
        counterparties[target].add(source)

    # --------------------------------------------------------
    # CREATE NODE SET
    # --------------------------------------------------------

    node_addresses = set(
        [searched_wallet]
        + list(node_transactions.keys())
    )

    nodes = []

    for address in node_addresses:

        entity = resolve_entity(address)

        node_txs = node_transactions.get(
            address,
            [],
        )

        risk_score, risk_reasons = calculate_node_risk(
            address,
            node_txs,
            searched_wallet,
        )

        is_exchange = entity.get("is_exchange", False)
        is_mixer = entity.get("is_mixer", False)
        entity_resolved = entity.get("entity_resolved", "Unknown")

        if is_exchange:

            display_name = (
                entity_resolved
                if entity_resolved != "Unknown"
                else "Known Exchange"
            )
            node_type = "Exchange"
            node_class = "exchange"

        elif address == searched_wallet:

            display_name = "Investigation Wallet"
            node_type = "Investigation Wallet"
            node_class = "investigation"

        elif is_mixer:

            display_name = (
                entity_resolved
                if entity_resolved != "Unknown"
                else "Mixer"
            )
            node_type = "Mixer"
            node_class = "mixer"

        else:

            display_name = "Intermediary Wallet"
            node_type = "Intermediary Wallet"
            node_class = "intermediary"

        nodes.append(
            {
                "id": address,

                "label": display_name,

                "display_name": display_name,

                "entity_resolved": (
                    entity_resolved
                    if entity_resolved != "Unknown"
                    else None
                ),

                "entity_type": entity.get("entity_type", "unknown"),

                "known": entity.get("known", False),

                "attribution_method": entity.get(
                    "attribution_method",
                    "none",
                ),

                "type": node_type,

                "node_class": node_class,

                "address": address,

                "full_address": address,

                "is_investigation_wallet": (
                    address == searched_wallet
                ),

                "risk_score": risk_score,

                "risk_status": (
                    "High"
                    if risk_score >= 70
                    else "Medium"
                    if risk_score >= 40
                    else "Low"
                ),

                "risk_reasons": risk_reasons,

                "is_exchange": is_exchange,

                "is_mixer": is_mixer,

                "hop": wallet_hops.get(
                    address,
                    1,
                ),

                "incoming_value": incoming_by_node[
                    address
                ],

                "outgoing_value": outgoing_by_node[
                    address
                ],

                "flow_value": flow_by_node[
                    address
                ],

                "counterparties": len(
                    counterparties[address]
                ),
            }
        )

    # --------------------------------------------------------
    # AGGREGATE EDGES
    # --------------------------------------------------------

    edge_groups: Dict[
        Tuple[str, str, str],
        Dict[str, Any]
    ] = {}

    for tx in all_transactions:

        key = (
            tx["source"],
            tx["target"],
            tx["asset"],
        )

        if key not in edge_groups:

            edge_groups[key] = {
                "id": (
                    f'{tx["source"]}-'
                    f'{tx["target"]}-'
                    f'{tx["asset"]}'
                ),

                "source": tx["source"],
                "target": tx["target"],

                "asset": tx["asset"],

                "amount": 0.0,

                "transaction_count": 0,

                "timestamp": tx["timestamp"],

                "latest_timestamp": tx[
                    "timestamp"
                ],

                "max_transaction": 0.0,

                "hop": tx["hop"],
            }

        group = edge_groups[key]

        group["amount"] += tx["amount"]

        group["transaction_count"] += 1

        group["max_transaction"] = max(
            group["max_transaction"],
            tx["amount"],
        )

        if tx["timestamp"]:
            group["latest_timestamp"] = (
                tx["timestamp"]
            )

    edges = []

    for edge in edge_groups.values():

        edges.append(
            {
                **edge,

                "label": (
                    f'{edge["amount"]:,.4f} '
                    f'{edge["asset"]}'
                ),

                "amount_label": (
                    f'{edge["amount"]:,.4f} '
                    f'{edge["asset"]}'
                ),

                "transactions": edge[
                    "transaction_count"
                ],
            }
        )

    # --------------------------------------------------------
    # PATTERNS
    # --------------------------------------------------------

    patterns = []

    for address in node_addresses:

        outgoing = [
            tx for tx in all_transactions
            if tx["source"] == address
        ]

        if len(outgoing) >= 3:

            destinations = {
                tx["target"]
                for tx in outgoing
            }

            if len(destinations) >= 2:

                patterns.append(
                    {
                        "type": "Fund Splitting",
                        "wallet": address,
                        "description": (
                            "Funds were distributed "
                            "towards multiple destinations."
                        ),
                    }
                )

    # --------------------------------------------------------
    # FUNDS BY ASSET
    # --------------------------------------------------------

    funds_by_asset = defaultdict(float)

    for tx in all_transactions:
        funds_by_asset[
            tx["asset"]
        ] += tx["amount"]

    # --------------------------------------------------------
    # ACTUAL HOPS
    # --------------------------------------------------------

    actual_hops = max(
        wallet_hops.values()
        or [0]
    )

    # --------------------------------------------------------
    # ROOT RISK
    # --------------------------------------------------------

    root_node = next(
        (
            node
            for node in nodes
            if node["id"] == searched_wallet
        ),
        None,
    )

    risk_score = (
        root_node["risk_score"]
        if root_node
        else 0
    )

    risk_status = (
        "High"
        if risk_score >= 70
        else "Medium"
        if risk_score >= 40
        else "Low"
    )

    # --------------------------------------------------------
    # RETURN
    # --------------------------------------------------------

    root_entity = resolve_entity(searched_wallet)

    return {
        "status": "success",

        "searched_wallet": searched_wallet,

        "entity_resolved": (
            root_entity.get("entity_resolved")
            if root_entity.get("entity_resolved") != "Unknown"
            else None
        ),

        "is_exchange": root_entity.get("is_exchange", False),

        "attribution_method": root_entity.get("attribution_method", "none"),

        "node_class": (
            "exchange"
            if root_entity.get("is_exchange", False)
            else "investigation"
        ),

        "display_name": (
            (root_entity.get("entity_resolved") or "Known Exchange")
            if root_entity.get("is_exchange", False)
            else "Investigation Wallet"
        ),

        "summary": {
            "risk_score": risk_score,

            "risk_status": risk_status,

            "total_nodes": len(nodes),

            "total_transactions": len(
                all_transactions
            ),

            "transactions_returned": len(
                all_transactions
            ),

            "hops_traced": actual_hops,

            "funds_by_asset": dict(
                funds_by_asset
            ),

            "total_funds": sum(
                funds_by_asset.values()
            ),
        },

        "topology": {
            "nodes": nodes,
            "edges": edges,
        },

        "transactions": all_transactions,

        "patterns": patterns,
    }


