def fetch_transfers(
    address: str,
    direction: str,
    category: str,
    max_count: int = MAX_TX_PER_REQUEST,
) -> List[Dict[str, Any]]:

    params = [
        {
            "fromBlock": "0x0",
            "toBlock": "latest",
            "category": [category],
            "withMetadata": True,
            "excludeZeroValue": True,
            "maxCount": hex(min(max_count, 100)),
        }
    ]

    if direction == "from":
        params[0]["fromAddress"] = address
    else:
        params[0]["toAddress"] = address

    result = alchemy_rpc(
        "alchemy_getAssetTransfers",
        params,
    )

    return result.get("transfers", [])


