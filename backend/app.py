# RISK
# ============================================================

def calculate_node_risk(
    address: str,
    txs: List[Dict[str, Any]],
    searched_wallet: str,
) -> Tuple[int, List[str]]:

    outgoing = [
        tx for tx in txs
        if tx["source"] == address
    ]

    incoming = [
        tx for tx in txs
        if tx["target"] == address
    ]

    counterparties = set()

    for tx in outgoing:
        counterparties.add(tx["target"])

    for tx in incoming:
        counterparties.add(tx["source"])

    score = 0
    reasons: List[str] = []

    if len(txs) >= 20:
        score += 15
        reasons.append("High transaction activity")

    if len(counterparties) >= 5:
        score += 15
        reasons.append("Multiple counterparties")

    if len(outgoing) >= 5:
        score += 15
        reasons.append("Multiple outgoing destinations")

    total_in = sum(
        tx["amount"]
        for tx in incoming
    )

    total_out = sum(
        tx["amount"]
        for tx in outgoing
    )

    if total_in > 0 and total_out > 0:
        forwarding_ratio = (
            min(total_out / total_in, 1)
        )

        if forwarding_ratio >= 0.8:
            score += 20
            reasons.append("High forwarding ratio")

    if address == searched_wallet:
        score += 10
        reasons.append("Investigation wallet")

    score = min(score, 100)

    if score >= 70:
        status = "High"
    elif score >= 40:
        status = "Medium"
    else:
        status = "Low"

    return score, reasons


