def validate_wallet(address: str) -> str:
    address = address.strip().lower()

    if not re.fullmatch(r"0x[a-f0-9]{40}", address):
        raise HTTPException(
            status_code=400,
            detail="Please enter a valid Ethereum wallet address.",
        )

    return address


def short_address(address: str) -> str:
    if not address:
        return ""

    if len(address) <= 16:
        return address

    return f"{address[:8]}...{address[-6:]}"


def safe_float(value: Any) -> float:
    try:
        return float(value or 0)
    except Exception:
        return 0.0


def format_asset(raw_asset: Any) -> str:
    asset = str(raw_asset or "ETH").strip()

    if not asset:
        return "ETH"

    # Remove obvious garbage generated by malformed metadata.
    if len(asset) > 20:
        return "TOKEN"

    return asset.upper()


def wei_to_eth(value: Any) -> float:
    try:
        return int(value or 0) / 10**18
    except Exception:
        return 0.0


def token_amount(value: Any, decimals: Any) -> float:
    try:
        raw = int(value or 0)
        dec = int(decimals if decimals is not None else 18)
        return raw / (10 ** dec)
    except Exception:
        return 0.0


