# FETCH BOTH SIDES
# ============================================================

def fetch_wallet_activity(
    wallet: str,
    hop: int,
) -> List[Dict[str, Any]]:

    transfers: List[Dict[str, Any]] = []

    # ERC20
    for direction in ("from", "to"):
        try:
            data = fetch_transfers(
                wallet,
                direction,
                "erc20",
            )

            for tx in data:
                normalized = normalize_transfer(
                    tx,
                    wallet,
                    hop,
                )

                if normalized:
                    transfers.append(normalized)

        except HTTPException:
            raise

    # Native ETH
    for direction in ("from", "to"):
        try:
            data = fetch_transfers(
                wallet,
                direction,
                "external",
            )

            for tx in data:
                normalized = normalize_transfer(
                    tx,
                    wallet,
                    hop,
                )

                if normalized:
                    transfers.append(normalized)

        except HTTPException:
            raise

    return transfers


